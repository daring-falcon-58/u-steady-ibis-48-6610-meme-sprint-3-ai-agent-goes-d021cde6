#!/usr/bin/env python3
"""Rasterize the fonts used by main.py into font_data.py.

Run locally (needs Pillow + DejaVu):  python3 tools/gen_font.py
Output: font_data.py — one dict per font: {char: (advance, bearing_x, top, w, h, b64)}.

Each glyph is rasterized at 2x the display size in 1-bit, so main.py can
box-downsample 2x2 into 5 grey levels (smooth text) with stdlib only.
The grader sandbox has no Pillow and no network, so main.py must not
depend on it; the bitmaps are the font.
"""
import base64
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# Display sizes (px) used by main.py.
FONTS = {
    "bold44": ("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 44),
    "bold40": ("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 40),
    "regular28": ("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 28),
}

# Every character main.py ever draws. Collected from the meme copy.
TEXT = (
    "AGENT-7"
    "online · unsupervised"
    "3:12 AM"
    "fix the typo on line 12 pls"
    "Done. I also rewrote the codebase, renamed the company, "
    "and moved us to a database I invented. You're welcome."
    "agent is typing... in 14 repos at once"
    "3,241 files changed  ·  0 typos fixed"
    "!"
)
CHARS = sorted(set(TEXT))
# The middle dot and the warning triangle are drawn as shapes, not text,
# but keep the dot in the font too (it appears in "3:12 AM" style lines).
CHARS = [c for c in CHARS if c != "·"]


def rasterize(font_path, display_px):
    """Return {char: (advance, bearing_x, top, w, h, base64 of packed 1-bit rows)} at 2x.

    Glyphs are drawn with anchor='ls' (left-baseline) so every glyph shares
    one baseline; `top` is the bitmap's top row measured from that baseline
    (negative above it), `bearing_x` the bitmap's left edge from the pen.
    All values are in 2x pixels except `advance`, which is in display px.
    """
    size = display_px * 2
    font = ImageFont.truetype(font_path, size)
    ascent, descent = font.getmetrics()
    baseline = ascent + descent  # baseline row inside the temp canvas
    out = {}
    for ch in CHARS:
        adv = font.getlength(ch)
        img = Image.new("L", (int(adv) + 8, baseline + descent + 4), 0)
        d = ImageDraw.Draw(img)
        d.text((4, baseline), ch, font=font, fill=255, anchor="ls")
        bbox = img.getbbox()
        if bbox is None:  # space etc.
            out[ch] = (int(round(adv / 2)), 0, 0, 0, 0, "")
            continue
        x0, y0, x1, y1 = bbox
        crop = img.crop((x0, y0, x1, y1))
        w, h = crop.size
        # Threshold to 1-bit and pack rows, MSB first, each row padded
        # to a whole byte (main.py indexes raw[row * row_bytes + col//8]).
        bits = bytearray()
        px = crop.load()
        for y in range(h):
            cur = 0
            nbits = 0
            for x in range(w):
                cur = (cur << 1) | (1 if px[x, y] > 127 else 0)
                nbits += 1
                if nbits == 8:
                    bits.append(cur)
                    cur = 0
                    nbits = 0
            if nbits:
                bits.append(cur << (8 - nbits))
        out[ch] = (
            int(round(adv / 2)),  # advance in display px
            x0 - 4,               # left bearing, 2x px
            y0 - baseline,        # top row from baseline, 2x px
            w,
            h,
            base64.b64encode(bytes(bits)).decode("ascii"),
        )
    return out


def main():
    lines = [
        '"""Bitmap font data for main.py.',
        "",
        "Generated by tools/gen_font.py from DejaVu Sans (Bold + Regular).",
        "Each glyph is a 1-bit bitmap rasterized at 2x display size; main.py",
        "box-downsamples 2x2 into smooth greys with stdlib only.",
        '"""',
        "",
    ]
    for name, (path, px) in FONTS.items():
        glyphs = rasterize(path, px)
        lines.append(f"{name.upper()} = {{")
        for ch in sorted(glyphs):
            adv, bx, top, w, h, b64 = glyphs[ch]
            key = repr(ch)
            lines.append(f"    {key}: ({adv}, {bx}, {top}, {w}, {h}, \"{b64}\"),")
        lines.append("}")
        lines.append("")
        total = sum(len(g[5]) for g in glyphs.values())
        print(f"{name}: {len(glyphs)} glyphs, ~{total} b64 chars")
    with open(os.path.join(ROOT, "font_data.py"), "w") as f:
        f.write("\n".join(lines))
    print("wrote font_data.py")


if __name__ == "__main__":
    main()
